/*
 * Some firmware requests server time via /rtdata.
 *
 * IMPORTANT:
 *
 * Returning:
 *
 *
 * causes the terminal to update its internal clock.
 *
 * We therefore only acknowledge the request.
 */
router.get('/rtdata', (req, res) => {
  const device = knownDevice(req.query.SN);

  if (!device) {
    return res
      .status(403)
      .type('text/plain')
      .send('Unregistered device serial number');
  }

  touch(device.id);

  return res
    .status(200)
    .type('text/plain')
    .send('OK');
});

/*
 * Real attendance push.
 *
 * Example body:
 *
 * TL495    2026-09-01 11:36:01    0    1    0    0    0
 *
 * The timestamp in ATTLOG is the timestamp generated by
 * the biometric terminal itself.
 */
router.post('/cdata', (req, res) => {
  const device = knownDevice(req.query.SN);

  if (!device) {
    return res
      .status(403)
      .type('text/plain')
      .send('Unregistered device serial number');
  }

  touch(device.id);

  const table = String(req.query.table || '').toUpperCase();

  // Ignore OPLOG and other non-attendance tables.
  if (table !== 'ATTLOG') {
    return res
      .status(200)
      .type('text/plain')
      .send('OK');
  }

  const body = typeof req.body === 'string' ? req.body : '';

  // Temporary/debug logging of raw attendance data.
  console.log('\n========== RAW ATTLOG ==========');
  console.log('Server time:', new Date().toString());
  console.log('SN:', device.serial_number);
  console.log('Query:', req.query);
  console.log('Body:\n' + body);
  console.log('===============================\n');

  const lines = body
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter(Boolean);

  let processed = 0;

  for (const line of lines) {
    const punchId = processPunchLine(device.serial_number, line);

    if (punchId !== null) {
      processed++;
    }
  }

  return res
    .status(200)
    .type('text/plain')
    .send(`OK:${processed}`);
});

export default router;